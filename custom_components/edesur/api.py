"""Asynchronous client for Edesur's unofficial web API.

Keep all HTTP details here: Home Assistant platforms must never build URLs,
parse authentication payloads or make raw requests themselves.
"""
from __future__ import annotations

from typing import Any
from urllib.parse import quote

from aiohttp import ClientError, ClientSession, ClientTimeout

from .const import API_BASE_URL, ORIGIN_CHANNEL


class EdesurError(Exception):
    """Base API error without personal or secret information."""


class EdesurAuthError(EdesurError):
    """Authentication failed or the session expired."""


class EdesurConnectionError(EdesurError):
    """Edesur could not be reached or returned invalid data."""


class EdesurApi:
    """Read-only client, except for the observed social-login POST."""

    def __init__(self, session: ClientSession) -> None:
        self._session = session
        self._token: str | None = None

    async def _request(
        self, method: str, path: str, *, payload: dict[str, Any] | None = None,
        authenticated: bool = True,
    ) -> Any:
        headers = {"Accept": "application/json"}
        if authenticated:
            if not self._token:
                raise EdesurAuthError("Missing authentication token")
            headers["Authorization"] = f"Bearer {self._token}"
        else:
            # These headers were observed in the website request. Their
            # necessity outside the browser has not yet been verified.
            headers.update({
                "Origin": "https://ov.edesur.com.ar",
                "Referer": "https://ov.edesur.com.ar/",
                "x-origin-channel": ORIGIN_CHANNEL,
            })
        try:
            async with self._session.request(
                method, f"{API_BASE_URL}{path}", headers=headers,
                json=payload, timeout=ClientTimeout(total=30),
            ) as response:
                if response.status in (401, 403):
                    raise EdesurAuthError("Authentication rejected by Edesur")
                if response.status >= 400:
                    raise EdesurConnectionError(f"Edesur returned HTTP {response.status}")
                try:
                    return await response.json(content_type=None)
                except (ValueError, UnicodeError) as err:
                    raise EdesurConnectionError("Edesur returned invalid JSON") from err
        except (ClientError, TimeoutError) as err:
            raise EdesurConnectionError("Could not communicate with Edesur") from err

    async def login_google(self, email: str, social_id: str) -> None:
        """Authenticate using the observed Google/social API payload.

        social_id is an input from the user's legitimate login flow, NOT
        a Google OAuth access token generated by this integration.
        """
        self._token = None
        data = await self._request(
            "POST", "/Usuario/login-social-media",
            payload={"socialMediaEmail": email, "socialMediaId": social_id},
            authenticated=False,
        )
        if not isinstance(data, dict) or not isinstance(data.get("token"), str) or not data["token"].strip():
            raise EdesurAuthError("Login did not return a token")
        self._token = data["token"].strip()

    async def get_accounts(self, email: str) -> list[str]:
        data = await self._request("GET", f"/Cliente/supply-retrieve/{quote(email, safe='')}")
        if not isinstance(data, dict) or not isinstance(data.get("supplies"), list):
            raise EdesurConnectionError("Unexpected accounts response")
        accounts = [
            str(item["contractAccount"]) for item in data["supplies"]
            if isinstance(item, dict) and item.get("contractAccount")
        ]
        return list(dict.fromkeys(accounts))

    async def get_client(self, account: str) -> Any:
        return await self._request("GET", f"/Cliente/get-client/{quote(account, safe='')}")

    async def get_readings(self, account: str) -> Any:
        return await self._request("GET", f"/Cliente/get-historical-readings/{quote(account, safe='')}")

    async def get_invoices(self, account: str) -> Any:
        return await self._request("GET", f"/Cliente/get-historical-invoices/{quote(account, safe='')}")

    async def get_payments(self, account: str) -> Any:
        return await self._request("GET", f"/Cliente/get-historical-payments/{quote(account, safe='')}")

    async def get_supply_status(self, account: str) -> Any:
        return await self._request("GET", f"/Cliente/get-cut-supply/{quote(account, safe='')}")

    async def get_debt(self, supply_number: str) -> Any:
        """Experimental: POST method and supply identifier need validation."""
        return await self._request("POST", "/PlanPagos/GetDeudaAsync", payload={
            "nroSuministro": supply_number,
            "tipoBusqueda": "nro_suministro",
            "valorBusqueda": supply_number,
        })
